//! Emit SQL INSERTs for `cell` (and optional `entity`) from procedural deck layout.
//!
//! Usage: `cargo run --bin export_deck_layout_sql > server/migrations/003_seed_cells.sql`

use ship_game::cell::{FloorMaterial, SideMaterial};
use ship_game::deck_layout::{deck_cell_layouts, DeckLayouts, CELL_SIZE_M};

fn wall_id(m: SideMaterial) -> i32 {
    match m {
        SideMaterial::Open => 1,
        SideMaterial::MarinePanel => 2,
        SideMaterial::Door => 3,
        SideMaterial::Window => 4,
    }
}

fn floor_id(m: FloorMaterial) -> i32 {
    match m {
        FloorMaterial::Carpet => 1,
        FloorMaterial::Wood => 2,
    }
}

fn ceiling_id(_z: u8) -> i32 {
    // Solid deck slab between levels
    2
}

fn emit_cells(layouts: &DeckLayouts) {
    println!("-- Generated by export_deck_layout_sql (do not edit by hand)");
    println!("BEGIN;");
    for (idx, cell) in layouts.cells.iter_occupied() {
        let x = idx.x as i32;
        let y = idx.y as i32;
        let z = idx.z as i32;
        println!(
            "INSERT INTO cell (x, y, z, bow_wall, stern_wall, port_wall, starboard_wall, floor, ceiling) VALUES ({x}, {y}, {z}, {}, {}, {}, {}, {}, {}) ON CONFLICT DO NOTHING;",
            wall_id(cell.side1),
            wall_id(cell.side3),
            wall_id(cell.side2),
            wall_id(cell.side4),
            floor_id(cell.floor),
            ceiling_id(idx.z),
        );
    }
    println!("COMMIT;");
}

fn emit_entities(layouts: &DeckLayouts) {
    if layouts.entities.is_empty() {
        return;
    }
    println!("BEGIN;");
    for (id, entity) in &layouts.entities {
        let (x, y, z) = entity.location;
        let kind = match entity.kind {
            ship_game::cell::EntityKind::SimHuman => "sim_human",
        };
        println!(
            "INSERT INTO entity (id, x, y, z, entity_type) VALUES ({}, {}, {}, {}, '{kind}') ON CONFLICT DO NOTHING;",
            id.0, x, y, z
        );
    }
    println!("SELECT setval('entity_id_seq', COALESCE((SELECT MAX(id) FROM entity), 1));");
    println!("COMMIT;");
}

fn main() {
    let layouts = deck_cell_layouts(CELL_SIZE_M);
    emit_cells(&layouts);
    emit_entities(&layouts);
}
